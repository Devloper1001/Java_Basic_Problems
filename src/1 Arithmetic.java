/*                          PROBLEM :- 1

  CREATE A PROGRAM THAT TAKE TWO NUMBER AND SHOW ALL RESULT OF ARITHMETIC OPERATOR ??


 */

class Problem1 {
    public static void main(String[] args) {
        int A = 8;
        int B = 5;

        System.out.println(A+B);
        System.out.println(A-B);
        System.out.println(A*B);
        System.out.println(A/B);
        System.out.println(A%B);

        double X = 8;
        double Y = 5;

        System.out.println(X+Y);
        System.out.println(X-Y);
        System.out.println(X*Y);
        System.out.println(X/Y);
        System.out.println(X%Y);

    }
}
